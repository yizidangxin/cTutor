def merge(name, new_entries, patches):
    path, data = load(name)
    entries = data["entries"]
    have_codes = set()
    have_titles = set()
    for e in entries:
        if e.get("code"):
            have_codes.add(e["code"].upper())
        for a in (e.get("aliases") or []):
            have_codes.add(a.upper())
        have_titles.add(e.get("title", ""))

    added, skipped = [], []
    for e in new_entries:
        code = (e.get("code") or "").upper()
        title = e.get("title", "")
        if (code and code in have_codes) or title in have_titles:
            skipped.append(title or code)
            continue
        entries.append(e)
        added.append(title)
        if code:
            have_codes.add(code)
        for a in (e.get("aliases") or []):
            have_codes.add(a.upper())
        have_titles.add(title)

    patched = []
    for e in entries:
        p = patches.get(e.get("title", ""))
        if p:
            e.update(p)
            patched.append(e["title"])

    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print("=" * 70)
    print("%s：新增 %d 条，跳过 %d 条（已存在），修订 %d 条"
          % (name, len(added), len(skipped), len(patched)))
    print("=" * 70)
    for t in added:
        print("  + " + t)
    if skipped:
        print("  已存在：")
        for t in skipped:
            print("    · %s" % t)
    for t in patched:
        print("  修订：%s" % t)
    return len(entries)


